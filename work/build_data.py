# Build docs/data.js (window.STAYS = [...]) from work/data/prepped.json + work/enrich/out/*.json.
# Run: python3 work/build_data.py
import glob, json, os, re

WORK = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(WORK)
IMG_BASE = "https://cdn.jalan.jp/jalan/images/"  # stripped from photo URLs to keep data.js small
STATION = {"lat": 35.6896, "lng": 139.7006, "radiusKm": 2}
# Gender-restricted plans (room name, plan name or room text). "女性専用フロア" (a women's floor) is not a restriction.
WOMEN = re.compile(r"女性限定|女性[２2]名限定|女性のみ|女性用|女性専用(?!の?フロア)")
MEN = re.compile(r"男性限定|男性のみ|男性用|男性専用(?!の?フロア)")
MEALS = {"食事なし": "Room only", "朝のみ": "Breakfast", "夕のみ": "Dinner only", "朝・夕": "Breakfast & dinner"}


def img(u):
    u = re.sub(r"/pict\w*?/", "/pict4L/", u, count=1)
    return u[len(IMG_BASE):] if u.startswith(IMG_BASE) else u


def clean(v):
    v = re.sub(r"\s+", " ", str(v or "")).strip()
    return "" if v in ("unknown", "none") else v


def compact(d):
    return {k: v for k, v in d.items() if v not in (None, "", [], {})}


def time_range(cin, cout):
    cin, cout = (cin or "").strip("～ "), (cout or "").strip("～ ")
    return " / ".join(x for x in [f"from {cin}" if cin else "", f"until {cout}" if cout else ""] if x)


def main():
    prepped = json.load(open(f"{WORK}/data/prepped.json"))
    enr = {}
    for f in sorted(glob.glob(f"{WORK}/enrich/out/*.json")):
        for o in json.load(open(f)):
            enr[str(o["yadNo"])] = o
    out, missing = [], []
    for q in prepped:
        e = enr.get(q["yadNo"])
        if not e:
            missing.append(q["yadNo"]); e = {}
        caps = e.get("photo_captions_en") or {}
        plans = []
        for r in q["plans"]:
            rm = (e.get("rooms") or {}).get(r["roomCd"], {})
            pl = (e.get("plans") or {}).get(r["planCd"], {})
            text = " ".join([r["planName"] or "", r["roomName"] or "", r["roomDetail"] or ""])
            gender = "women" if WOMEN.search(text) else "men" if MEN.search(text) else None
            photos = [img(u) for u in r["roomImages"] + r["planImages"] if "/Y%s/" % q["yadNo"] in u]
            plans.append(compact({
                "name": clean(pl.get("plan_name_en")) or r["planName"], "nameJp": r["planName"],
                "meals": pl.get("meals") or MEALS.get(r["meal"], r["meal"]), "breakfast": clean(pl.get("breakfast_en")),
                "notes": clean(pl.get("notes_en")), "price": r["total"], "cancel": r["cancel"], "roomsLeft": r["roomsLeft"],
                "oneNight": r["oneNight"] or None, "gender": gender,
                "room": clean(rm.get("room_en")) or r["roomName"], "roomJp": r["roomName"],
                "occupancy": rm.get("occupancy") or "private", "style": clean(rm.get("style")), "bedding": clean(rm.get("bedding")),
                "size": clean(rm.get("size")), "bathroom": rm.get("bathroom") or "unknown", "smoking": rm.get("smoking") or "unknown",
                "photo": photos[0] if photos else None, "photos": list(dict.fromkeys(photos)),
                "planCd": r["planCd"], "roomCd": r["roomCd"],
            }))
        out.append(compact({
            "id": q["yadNo"], "name": clean(e.get("name_en")) or q["name"], "nameJp": q["name"], "type": e.get("type") or "other",
            "typeNote": clean(e.get("type_note")), "summary": clean(e.get("summary_en")), "access": clean(e.get("access_en")),
            "address": q["address"], "lat": q["lat"], "lng": q["lng"], "dist": q["distKm"],
            "rating": q["rating"], "reviews": q["reviews"], "scores": compact(q["scores"]),
            "strong": e.get("strong_points") or [], "watch": clean(e.get("watch_outs")), "reviewSummary": clean(e.get("review_summary_en")),
            "checkInOut": time_range(q["checkin"], q["checkout"]),
            "photos": [[img(u), clean(caps.get(a)) or a] for u, a in q["photos"]],
            "plans": plans,
        }))
    js = ("// Generated by work/build_data.py; do not edit.\n"
          f"window.IMG_BASE = {json.dumps(IMG_BASE)};\nwindow.STATION = {json.dumps(STATION)};\nwindow.STAYS = "
          + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    open(f"{ROOT}/docs/data.js", "w").write(js)
    prices = [p["price"] for r in out for p in r["plans"]]
    print(json.dumps({"stays": len(out), "plans": len(prices), "price": [min(prices), max(prices)], "missing_enrichment": missing,
                      "types": {t: sum(r["type"] == t for r in out) for t in sorted({r["type"] for r in out})}, "bytes": len(js.encode())}))


if __name__ == "__main__":
    main()
